// The AI-readable docs (site/src/lib/llms.ts): the page transform on small fixtures, and the index and
// full text built from the real pages in nav.ts.
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PAGES, sidebar, type MetaNode } from "../site/src/nav.ts";
import { SITE, loadLlms, mdUrl, orderedPages, pageMarkdown, titleOf, type LinkContext } from "../site/src/lib/llms.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const nodes: MetaNode[] = JSON.parse(readFileSync(join(ROOT, "meta-kb/data/nodes.json"), "utf8"));

const ctx: LinkContext = {
  source: "docs/learn/facets.md",
  routeFor: (p) => (p === "docs/GLOSSARY.md" ? "/reference/glossary/" : p === "docs/learn/hierarchy.md" ? "/learn/hierarchy/" : undefined),
  isDirectory: (p) => p === "examples/wine",
};

test("llms: an okb-graph embed becomes its fallback text", () => {
  const md = 'Before.\n\n<okb-graph src="/data/x.json" label="L">\n<p>The graph shows two drinks.</p>\n<ul>\n<li>A is a kind of B.</li>\n<li>C contains D.</li>\n</ul>\n</okb-graph>\n\nAfter.\n';
  assert.equal(pageMarkdown(md, ctx), "Before.\n\nThe graph shows two drinks.\n\n- A is a kind of B.\n- C contains D.\n\nAfter.\n");
});

test("llms: Mermaid blocks keep their source, and links inside code are not rewritten", () => {
  const md = "```mermaid\nflowchart LR\n  A[\"[x](hierarchy.md)\"] --> B\n```\n\nUse `[x](hierarchy.md)` here.\n";
  assert.equal(pageMarkdown(md, ctx), md);
});

test("llms: HTML comments are dropped", () => {
  const md = "# Rules\n\n<!-- Generated by `pnpm run docs`. Don't edit. -->\n\nText.\n";
  assert.equal(pageMarkdown(md, ctx), "# Rules\n\nText.\n");
});

test("llms: layout-only div lines are dropped", () => {
  assert.equal(pageMarkdown('<div class="cheat-card">\n\nRun it:\n\n</div>\n', ctx), "Run it:\n");
});

test("llms: links to pages become absolute .md URLs, and anchors are kept", () => {
  const out = pageMarkdown("See [hierarchy](hierarchy.md) and [class](../GLOSSARY.md#concept-class).\n", ctx);
  assert.equal(out, `See [hierarchy](${SITE}/learn/hierarchy.md) and [class](${SITE}/reference/glossary.md#concept-class).\n`);
});

test("llms: links to files and folders that are not pages go to GitHub; external links and site paths stay or are made absolute", () => {
  const out = pageMarkdown("[wine](../../examples/wine) [src](../../src/cli.ts) [readme](../../README.md) [ext](https://example.com/a) [data](/data/espresso.json) [here](#top)\n", ctx);
  const gh = "https://github.com/alanbsmith/ontology-kit";
  assert.equal(out, `[wine](${gh}/tree/main/examples/wine) [src](${gh}/blob/main/src/cli.ts) [readme](${gh}/blob/main/README.md) [ext](https://example.com/a) [data](${SITE}/data/espresso.json) [here](#top)\n`);
});

test("llms: reference definitions and titled links are rewritten", () => {
  const out = pageMarkdown('[a]: hierarchy.md\n\n[b](hierarchy.md "Title")\n', ctx);
  assert.equal(out, `[a]: ${SITE}/learn/hierarchy.md\n\n[b](${SITE}/learn/hierarchy.md "Title")\n`);
});

test("llms: titleOf is the first level-1 heading outside code", () => {
  assert.equal(titleOf("```\n# no\n```\n# Yes\n", "x"), "Yes");
  assert.equal(titleOf("no heading", "Label"), "Label");
  assert.equal(mdUrl("/learn/facets/"), `${SITE}/learn/facets.md`);
});

const site = loadLlms(ROOT, nodes);
const linkedRoutes = [...site.index.matchAll(/^- \[[^\]]*\]\((https:\/\/ontology-kit\.dev[^)]*)\): /gm)].map((m) => m[1]);

test("llms: every page has a one-sentence summary", () => {
  for (const p of PAGES) {
    assert.ok(typeof p.summary === "string" && p.summary.trim().length > 0, `${p.route} has no summary`);
    assert.ok(/[.?]$/.test(p.summary), `${p.route}: the summary should be a sentence`);
    assert.ok(p.summary.split(/\s+/).length <= 40, `${p.route}: the summary is too long`);
  }
});

test("llms: llms.txt lists every page once, in sidebar order, with its summary", () => {
  const expected = orderedPages(nodes).map((p) => mdUrl(p.route));
  assert.equal(new Set(linkedRoutes).size, linkedRoutes.length);
  assert.equal(new Set(expected).size, PAGES.length);
  // Grouped like the sidebar: the pages of each group, in order, make up the whole list.
  assert.deepEqual([...linkedRoutes].sort(), [...expected].sort());
  assert.deepEqual(linkedRoutes, expected);
  assert.deepEqual(
    [...site.index.matchAll(/^## (.+)$/gm)].map((m) => m[1]),
    sidebar(nodes).map((g) => g.label),
  );
  for (const p of PAGES) assert.ok(site.index.includes(`${mdUrl(p.route)}): ${p.summary}`), `${p.route} summary missing`);
});

test("llms: every .md route llms.txt links to has a page endpoint", () => {
  assert.ok(existsSync(join(ROOT, "site/src/pages/[...slug].md.ts")), "site/src/pages/[...slug].md.ts is missing");
  for (const url of linkedRoutes) {
    const route = url.slice(SITE.length).replace(/\.md$/, "/");
    assert.ok(PAGES.some((p) => p.route === route), `${url} has no page`);
    assert.ok(site.pages.has(route));
  }
});

test("llms: llms-full.txt has every page once, in order, and no leftovers of the web page", () => {
  const routes = [...site.full.matchAll(/^# Page: (\/\S*)$/gm)].map((m) => m[1]);
  assert.deepEqual(routes, orderedPages(nodes).map((p) => p.route));
  assert.ok(!site.full.includes("<okb-graph"));
  assert.ok(!site.full.includes("<!--"));
  assert.ok(!/\]\((?!https?:|#|mailto:)[^)]*\.md/.test(site.full), "a relative .md link is left");
});

test("llms: no page summary states a duration (the page header computes it)", () => {
  // Hand-written times drift from the estimate in site/src/lib/reading-time.ts, so summaries leave them out.
  const duration = /\b(\d+|one|two|three|four|five|six|seven|eight|nine|ten)[- ]?(minutes?|mins?|hours?|hrs?)\b|\b(minute|hour)-long\b|\b(five|ten|\d+)-minute\b/i;
  for (const p of PAGES) assert.ok(!duration.test(p.summary), `${p.route}: the summary states a duration: ${p.summary}`);
});
