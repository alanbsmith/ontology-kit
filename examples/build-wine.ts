/**
 * Builds the Ontology 101 wine & food ontology from scratch, one okb command at a time.
 * The commands live in examples/wine/tutorial-src/*.md, where they sit among the prose of the
 * wine tutorial. This script runs them (examples/lib/tutorial.ts), which writes the ontology, the
 * tutorial pages (examples/wine/tutorial/), a graph snapshot after each step, and a transcript
 * (examples/wine/TRANSCRIPT.md). Run it as an end-to-end test (npm run example): it fails if a
 * command fails or the final ontology has errors.
 */
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildTutorial } from "./lib/tutorial.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIR = join(ROOT, "examples", "wine");
// Every date okb records in the example (created, decision dates) is this day, so
// rebuilding it gives identical files on any day and in any time zone.
const EXAMPLE_DATE = "2026-09-23";

buildTutorial({
  dir: DIR,
  date: EXAMPLE_DATE,
  transcript: {
    title: "Worked example: the Ontology 101 wine & food ontology",
    intro: [
      "Generated by `npm run example` (examples/build-wine.ts) from the tutorial sources in examples/wine/tutorial-src. Every command below was really run, and the output under it is what okb printed. The prose around the commands is in the tutorial pages (examples/wine/tutorial).",
      "It follows the paper's running example. Where the paper leaves a detail open, the choice made here is recorded as a design decision.",
    ],
  },
});

let final: { findings: { severity: string; rule: string; message: string }[] };
try {
  final = JSON.parse(execFileSync(process.execPath, [join(ROOT, "src", "cli.ts"), "validate", "--all", "--json"], { cwd: DIR, encoding: "utf8" }));
} catch (e: any) {
  final = JSON.parse(e.stdout);
}
const errors = final.findings.filter((f) => f.severity === "error");
console.log(`Built examples/wine (${final.findings.length} finding(s), ${errors.length} error(s)). Tutorial: examples/wine/tutorial, transcript: examples/wine/TRANSCRIPT.md`);
if (errors.length) {
  for (const e of errors) console.error("  ✗", e.rule, e.message);
  process.exit(1);
}
