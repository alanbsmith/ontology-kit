/**
 * Builds the espresso ontology (a small coffee-drinks ontology for the landing page and the Learn
 * course) from scratch, one okb command at a time. The commands live in
 * examples/espresso/tutorial-src/*.md. This script runs them through the tutorial engine
 * (examples/lib/tutorial.ts), which writes the ontology, the tutorial pages, a graph snapshot after
 * each step and a transcript. It fails if a command fails or the
 * final ontology has errors. Unlike the wine ontology, it keeps one warning on purpose, so the
 * landing page has a real finding to show.
 */
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildTutorial } from "./lib/tutorial.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIR = join(ROOT, "examples", "espresso");
// Every date okb records in the example is this day, so rebuilding gives identical files on any day.
const EXAMPLE_DATE = "2026-09-23";

buildTutorial({
  dir: DIR,
  date: EXAMPLE_DATE,
  transcript: {
    title: "Worked example: the espresso ontology",
    intro: [
      "Generated by `pnpm example` (examples/build-espresso.ts) from the sources in examples/espresso/tutorial-src. Every command below was really run, and the output under it is what okb printed.",
      "It's a small ontology of coffee drinks. One warning is left on purpose, as a finding to look at.",
    ],
  },
});

let final: { findings: { severity: string; rule: string; message: string }[] };
try {
  final = JSON.parse(execFileSync(process.execPath, [join(ROOT, "src", "cli.ts"), "validate", "--all", "--json"], { cwd: DIR, encoding: "utf8" }));
} catch (e: any) {
  final = JSON.parse(e.stdout);
}
const errors = final.findings.filter((f) => f.severity === "error");
console.log(`Built examples/espresso (${final.findings.length} finding(s), ${errors.length} error(s)). Transcript: examples/espresso/TRANSCRIPT.md`);
if (errors.length) {
  for (const e of errors) console.error("  ✗", e.rule, e.message);
  process.exit(1);
}
