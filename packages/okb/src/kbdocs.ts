/**
 * `okb docs`: reference pages for a domain ontology, so people can read its structure and rules
 * without the CLI. `kbDocs` is a pure function from a loaded `Ontology` to a map of file name to
 * Markdown (no disk, no clock), so the same ontology always gives the same pages and they can be
 * committed and checked for drift. `writeKbDocs` writes them.
 *
 * Layout: `index.md` (scope, questions, class tree, decisions), `classes/<anchor>.md` (one per
 * class), `rules.md`, `sources.md`. Every item gets an `<a id>` from its node id with `.` replaced
 * by `-` (`rule.breve-uses` → `rule-breve-uses`), the scheme gendocs.ts uses for the meta-KB docs.
 * Links are relative, so they work on GitHub and in a content collection that keeps the folder.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { OkbError, nameOrText, type ClassNode, type DesignDecisionNode, type OkbNode, type Ontology, type RuleNode, type SourceLocationNode, type SourceNode } from "@ontology-kit/format";
import { anchorId } from "./site.ts";

export type DocFiles = Record<string, string>;

export const BANNER = "<!-- Generated by okb docs. Do not edit: change the knowledge base and run okb docs again. -->";
const byText = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const byName = <T extends OkbNode>(a: T, b: T) => byText((nameOrText(a) ?? a.id).toLowerCase(), (nameOrText(b) ?? b.id).toLowerCase()) || byText(a.id, b.id);
const anchor = (id: string) => `<a id="${anchorId(id)}"></a>`;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const oneLine = (s: string) => s.replace(/\s*\n\s*/g, " ").trim();
const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? "" : "s"}`;

/** Where a page lives, relative to the docs root. */
const classFile = (id: string) => `classes/${anchorId(id)}.md`;

type Page = "index" | "class" | "rules" | "sources";
const HERE: Record<Page, string> = { index: "", class: "../", rules: "", sources: "" };

class Links {
  private ont: Ontology;
  private page: Page;
  private root: string;
  constructor(ont: Ontology, page: Page) {
    this.ont = ont;
    this.page = page;
    this.root = HERE[page];
  }
  index = () => `${this.root}index.md`;
  rules = (id?: string) => `${this.root}rules.md${id ? `#${anchorId(id)}` : ""}`;
  sources = (id?: string) => `${this.root}sources.md${id ? `#${anchorId(id)}` : ""}`;
  /** A class page, from this page: siblings in classes/ link without the folder. */
  cls = (id: string) => (this.page === "class" ? `${anchorId(id)}.md` : classFile(id));

  /** A link to a node's page, or its plain name when it has none. */
  node(id: string): string {
    const n = this.ont.get(id);
    if (!n) return `\`${id}\``;
    const name = nameOrText(n) ?? id;
    if (n.type === "Class") return `[${name}](${this.cls(id)})`;
    if (n.type === "Instance") {
      const home = [...this.ont.targets(id, "INSTANCE_OF")].sort(byText)[0];
      return home && this.ont.get(home)?.type === "Class" ? `[${name}](${this.cls(home)}#${anchorId(id)})` : name;
    }
    if (n.type === "Rule") return `[${name}](${this.rules(id)})`;
    return name;
  }
}

const slotName = (ont: Ontology, id: string) => nameOrText(ont.require(id)) ?? id;

function valueText(ont: Ontology, l: Links, v: unknown): string {
  if (typeof v === "string" && ont.get(v)) return l.node(v);
  return String(v);
}

function listValues(ont: Ontology, l: Links, vs: unknown[]): string {
  return vs.map((v) => valueText(ont, l, v)).join(", ");
}

/** The quote behind a rule or other node, as links to the sources page (and the source's own link when it has one). */
function quoteLines(ont: Ontology, l: Links, nodeId: string): string[] {
  const locs = ont.targets(nodeId, "CITES").map((id) => ont.get(id)).filter((n): n is SourceLocationNode => n?.type === "SourceLocation");
  if (!locs.length) return ["- Source: none cited."];
  return locs.flatMap((loc) => {
    const where = loc.locator ?? loc.id;
    const ext = loc.sourceLink ?? loc.pageLink;
    return [`- Source: [${where}${loc.lines ? `, line ${loc.lines}` : loc.page !== undefined ? `, page ${loc.page}` : ""}](${l.sources(loc.id)})${ext ? ` ([original](${ext}))` : ""}`, `  > ${oneLine(loc.quote)}`];
  });
}

function ruleBlock(ont: Ontology, l: Links, rule: RuleNode, level: number, opts: { governs?: boolean } = {}): string[] {
  const out = [anchor(rule.id), `${"#".repeat(level)} ${rule.name}`, "", `**${rule.modality.replace("_", " ")}.** ${rule.statement}`, ""];
  const bullets: string[] = [];
  const governs = ont.targets(rule.id, "GOVERNS");
  if (opts.governs && governs.length) bullets.push(`- Governs: ${governs.map((g) => l.node(g)).join(", ")}`);
  const v = rule.verification?.status;
  bullets.push(`- Verification: ${v ? v.toLowerCase() : "not verified"}${rule.authored ? " (written by the owner)" : ""}`);
  for (const [slotId, val] of Object.entries(rule.values ?? {})) bullets.push(`- ${slotName(ont, slotId)}: ${[val].flat().join(", ")}`);
  const refines = ont.targets(rule.id, "REFINES");
  if (refines.length) bullets.push(`- Refines: ${refines.map((r) => l.node(r)).join(", ")}`);
  bullets.push(...quoteLines(ont, l, rule.id));
  return [...out, ...bullets, ""];
}

function rulesGoverning(ont: Ontology, classId: string): RuleNode[] {
  return ont.ofType("Rule").filter((r) => ont.targets(r.id, "GOVERNS").includes(classId));
}

function decisionsAbout(ont: Ontology, id: string): DesignDecisionNode[] {
  return ont.ofType("DesignDecision").filter((d) => ont.targets(d.id, "ABOUT").includes(id)).sort(byName);
}

function decisionBlock(d: DesignDecisionNode, level: number): string[] {
  const out = [anchor(d.id), `${"#".repeat(level)} ${d.title}`, "", `**Decision.** ${d.decision}`, ""];
  if (d.question) out.push(`**Question.** ${d.question}`, "");
  if (d.rationale) out.push(`**Why.** ${d.rationale}`, "");
  if (d.alternatives?.length) out.push(`**Alternatives considered.** ${d.alternatives.join("; ")}`, "");
  if (d.metaRules?.length) out.push(`**Explains the rules:** ${d.metaRules.map((r) => `\`${r}\``).join(", ")}`, "");
  out.push(`Date: ${d.date}`, "");
  return out;
}

function classTree(ont: Ontology, l: Links, ids: string[], seen: Set<string>, depth = 0): string[] {
  const out: string[] = [];
  for (const id of ids.map((i) => ont.require(i, "Class")).sort(byName).map((c) => c.id)) {
    const again = seen.has(id);
    out.push(`${"  ".repeat(depth)}- ${l.node(id)}${again ? " (see above)" : ""}`);
    if (again) continue;
    seen.add(id);
    out.push(...classTree(ont, l, ont.children(id), seen, depth + 1));
  }
  return out;
}

function indexPage(ont: Ontology): string {
  const l = new Links(ont, "index");
  const m = ont.meta;
  const out = [BANNER, "", `# ${m.name}`, ""];
  if (m.purpose) out.push(m.purpose, "");
  out.push("## Scope", "");
  const row = (k: string, v: string | string[]) => {
    const text = Array.isArray(v) ? v.join(", ") : v;
    if (text) out.push(`- **${k}:** ${text}`);
  };
  row("Domain", m.domain);
  row("Users", m.users);
  row("Maintainers", m.maintainers);
  row("Out of scope", m.outOfScope);
  row("Kind", m.kind);
  if (ont.manifest.version) row("Version", ont.manifest.version);
  out.push("");

  const cqs = ont.numbered("CompetencyQuestion");
  if (cqs.length) {
    out.push("## Competency questions", "");
    cqs.forEach((q, i) => out.push(`${i + 1}. ${nameOrText(q)}`));
    out.push("");
  }

  const rules = ont.ofType("Rule").length;
  const sources = ont.ofType("Source").length;
  out.push("## Classes", "");
  const seen = new Set<string>();
  out.push(...classTree(ont, l, ont.roots(), seen));
  const orphans = ont.ofType("Class").filter((c) => !seen.has(c.id)).map((c) => c.id);
  if (orphans.length) out.push(...classTree(ont, l, orphans, seen));
  if (!ont.ofType("Class").length) out.push("No classes yet.");
  out.push("");

  const decisions = ont.numbered("DesignDecision") as DesignDecisionNode[];
  if (decisions.length) {
    out.push("## Design decisions", "");
    for (const d of decisions) {
      const about = ont.targets(d.id, "ABOUT").filter((a) => ont.get(a)?.type === "Class");
      out.push(`- ${d.title}: ${d.decision}${about.length ? ` (about ${about.map((a) => l.node(a)).join(", ")})` : ""}`);
    }
    out.push("");
  }

  out.push("## More", "", `- [Rules](rules.md): ${plural(rules, "rule")}`, `- [Sources](sources.md): ${plural(sources, "source")}`, "");
  return out.join("\n");
}

function classPage(ont: Ontology, c: ClassNode): string {
  const l = new Links(ont, "class");
  const out = [BANNER, "", anchor(c.id), `# ${c.name}`, ""];
  out.push(`[Index](${l.index()}) · [Rules](${l.rules()}) · [Sources](${l.sources()})`, "");
  if (c.description) out.push(c.description, "");
  const bullets: string[] = [];
  if (c.synonyms?.length) bullets.push(`- Also called: ${c.synonyms.join(", ")}`);
  if (c.formerNames?.length) bullets.push(`- Formerly: ${c.formerNames.join(", ")}`);
  if (c.abstract) bullets.push("- Abstract: it has no members of its own, only its subclasses do.");
  const parents = ont.parents(c.id).sort(byText);
  if (parents.length) bullets.push(`- Is a: ${parents.map((p) => l.node(p)).join(", ")}`);
  const kids = ont.children(c.id).sort(byText);
  if (kids.length) bullets.push(`- Subclasses: ${kids.map((k) => l.node(k)).join(", ")}`);
  const disjoint = [...ont.targets(c.id, "DISJOINT_WITH"), ...ont.sources(c.id, "DISJOINT_WITH")].sort(byText);
  if (disjoint.length) bullets.push(`- Disjoint with: ${disjoint.map((d) => l.node(d)).join(", ")}`);
  if (bullets.length) out.push(...bullets, "");

  // Slots: own first, then inherited from the nearest ancestors.
  const nearest = [...ont.ancestors(c.id)]; // nearest first: it decides which class's value applies
  const ancestors = [...nearest].sort(byText);
  const context = [c.id, ...nearest];
  const slotIds = ont.applicableSlots(c.id);
  if (slotIds.length) {
    out.push("## Slots", "", "| Slot | Kind | From | Type | Allowed values | Count | Class value |", "| --- | --- | --- | --- | --- | --- | --- |");
    const rows = slotIds.map((sid) => ({ sid, s: ont.require(sid, "Slot") })).sort((a, b) => Number(ont.ownSlots(c.id).includes(b.sid)) - Number(ont.ownSlots(c.id).includes(a.sid)) || byName(a.s, b.s));
    for (const { sid, s } of rows) {
      const own = ont.ownSlots(c.id).includes(sid);
      const from = own ? "own" : "inherited from " + ont.domain(sid).filter((d) => ancestors.includes(d)).sort(byText).map((d) => l.node(d)).join(", ");
      const f = ont.effectiveFacets(sid, context);
      const rel = f.valueType === "Instance";
      const type = rel ? `link to ${f.range.length ? f.range.map((r) => l.node(r)).join(" or ") : "anything"}` : (f.valueType ?? "unset");
      const count = `${f.min}..${f.max ?? "*"}`;
      const note = f.overriddenBy.length ? ` (narrowed by ${f.overriddenBy.map((o) => l.node(o)).join(", ")})` : "";
      const fixed = ont.statedValues(c.id, sid);
      const inheritedFixed = fixed.length ? null : ont.inheritedFixed(sid, ancestors);
      const classValue = fixed.length ? listValues(ont, l, fixed) : inheritedFixed ? `${listValues(ont, l, inheritedFixed.values)} (from ${l.node(inheritedFixed.cls)})` : "";
      out.push(`| ${cell(`${anchor(`${c.id}.${sid}`)}${s.name}`)} | ${rel ? "relationship" : "property"} | ${cell(from)} | ${cell(type)} | ${cell(f.allowedValues ? f.allowedValues.join(", ") + note : note.trim())} | ${count} | ${cell(classValue)} |`);
    }
    out.push("");
    const described = rows.filter(({ s }) => s.description);
    if (described.length) {
      for (const { s } of described) out.push(`- **${s.name}:** ${s.description}`);
      out.push("");
    }
  }

  // Rules: this class's own, then those inherited from ancestors.
  const own = rulesGoverning(ont, c.id).sort(byName);
  const inherited = ancestors.flatMap((a) => rulesGoverning(ont, a).map((r) => ({ r, a }))).sort((x, y) => byName(x.r, y.r));
  if (own.length || inherited.length) {
    out.push("## Rules", "");
    for (const r of own) out.push(...ruleSummary(ont, l, r));
    for (const { r, a } of inherited) out.push(...ruleSummary(ont, l, r, a));
  }

  const members = ont.ofType("Instance").filter((i) => ont.targets(i.id, "INSTANCE_OF").includes(c.id)).sort(byName);
  if (members.length) {
    out.push("## Instances", "");
    for (const i of members) {
      const parts: string[] = [];
      for (const sid of ont.applicableSlots(i.id)) {
        const vals = ont.statedValues(i.id, sid);
        if (vals.length) parts.push(`${slotName(ont, sid)}: ${listValues(ont, l, vals)}`);
      }
      out.push(`- ${anchor(i.id)}**${i.name}**${i.description ? `. ${i.description}` : ""}${parts.length ? ` (${parts.join("; ")})` : ""}`);
    }
    out.push("");
  }

  const decisions = decisionsAbout(ont, c.id);
  if (decisions.length) {
    out.push("## Decisions", "");
    for (const d of decisions) out.push(...decisionBlock(d, 3));
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** A rule on a class page: modality, statement and the link to its quote. */
function ruleSummary(ont: Ontology, l: Links, rule: RuleNode, from?: string): string[] {
  const loc = ont.targets(rule.id, "CITES").map((id) => ont.get(id)).find((n): n is SourceLocationNode => n?.type === "SourceLocation");
  const quote = loc ? ` Source: [${loc.locator ?? loc.id}${loc.lines ? `, line ${loc.lines}` : ""}](${l.sources(loc.id)}).` : " Source: none cited.";
  return [`- [${rule.name}](${l.rules(rule.id)}) (${from ? `inherited from ${l.node(from)}, ` : ""}${rule.modality.replace("_", " ")}): ${rule.statement}${quote}`, ...(loc ? [`  > ${oneLine(loc.quote)}`] : []), ""];
}

function rulesPage(ont: Ontology): string {
  const l = new Links(ont, "rules");
  const rules = ont.ofType("Rule").sort(byName);
  const out = [BANNER, "", "# Rules", "", `[Index](index.md) · [Sources](sources.md)`, ""];
  if (!rules.length) return [...out, "This knowledge base has no rules yet.", ""].join("\n");
  out.push(`${plural(rules.length, "rule")}. Each one links to the quote it rests on.`, "");
  for (const r of rules) out.push(...ruleBlock(ont, l, r, 2, { governs: true }));
  return out.join("\n").trimEnd() + "\n";
}

function sourcesPage(ont: Ontology): string {
  const l = new Links(ont, "sources");
  const out = [BANNER, "", "# Sources", "", `[Index](index.md) · [Rules](rules.md)`, ""];
  const sources = ont.ofType("Source").sort(byName);
  if (!sources.length) return [...out, "This knowledge base has no registered sources yet.", ""].join("\n");
  const locsOf = (s: SourceNode) =>
    ont.sources(s.id, "PART_OF").map((id) => ont.get(id)).filter((n): n is SourceLocationNode => n?.type === "SourceLocation")
      .sort((a, b) => (a.startLine ?? Infinity) - (b.startLine ?? Infinity) || byText(a.id, b.id));
  for (const s of sources) {
    out.push(anchor(s.id), `## ${s.title}`, "");
    const meta: string[] = [];
    if (s.localPath) meta.push(`- File: \`${s.localPath}\``);
    if (s.format) meta.push(`- Format: ${s.format}`);
    if (s.url) meta.push(`- URL: <${s.url}>`);
    if (s.repoUrl) meta.push(`- Repository: <${s.repoUrl}>`);
    if (meta.length) out.push(...meta, "");
    for (const loc of locsOf(s)) {
      out.push(anchor(loc.id), `### ${loc.locator ?? loc.id}`, "");
      const ext = loc.sourceLink ?? loc.pageLink;
      out.push(`> ${oneLine(loc.quote)}`, "");
      const facts = [loc.lines ? `line ${loc.lines}` : null, loc.page !== undefined ? `page ${loc.page}` : null, loc.blockKind ?? null].filter(Boolean).join(", ");
      if (facts || ext) out.push(`${facts}${ext ? `${facts ? " · " : ""}[original](${ext})` : ""}`, "");
      const citing = ont.sources(loc.id, "CITES").map((id) => ont.require(id)).sort(byName);
      if (citing.length) out.push(`Cited by: ${citing.map((n) => (n.type === "Rule" ? `rule ${l.node(n.id)}` : `${n.type.toLowerCase()} ${l.node(n.id)}`)).join(", ")}`, "");
    }
  }
  // Quotes whose source is missing from the file still need a landing place for rule links.
  const loose = ont.ofType("SourceLocation").filter((loc) => !ont.targets(loc.id, "PART_OF").some((id) => ont.get(id)?.type === "Source"));
  if (loose.length) {
    out.push("## Quotes without a source", "");
    for (const loc of loose.sort(byName)) out.push(anchor(loc.id), `### ${loc.locator ?? loc.id}`, "", `> ${oneLine(loc.quote)}`, "");
  }
  return out.join("\n").trimEnd() + "\n";
}

/** Every page for the ontology: file name (relative to the docs folder) → Markdown. */
export function kbDocs(ont: Ontology): DocFiles {
  const files: DocFiles = {
    "index.md": indexPage(ont),
    "rules.md": rulesPage(ont),
    "sources.md": sourcesPage(ont),
  };
  for (const c of ont.ofType("Class")) files[classFile(c.id)] = classPage(ont, c);
  return files;
}

/** Write the pages into `dir`, removing pages an earlier run wrote (they carry the banner) that no longer exist. Other files stay. Returns the file names. */
export function writeKbDocs(ont: Ontology, dir: string): string[] {
  const files = kbDocs(ont);
  for (const old of listMarkdown(dir)) if (!(old in files) && readFileSync(join(dir, old), "utf8").startsWith(BANNER)) rmSync(join(dir, old));
  return writePages(dir, files);
}

/**
 * Write pages into `dir` (creating folders) and leave every other file alone. A page never replaces a file
 * okb didn't write (no banner): that file is named in the error and nothing is written. Returns the file names.
 */
export function writePages(dir: string, files: DocFiles): string[] {
  const yours = Object.keys(files).filter((name) => {
    try {
      return !readFileSync(join(dir, name), "utf8").startsWith(BANNER);
    } catch {
      return false; // not there yet
    }
  });
  if (yours.length) {
    throw new OkbError(`${dir} already has ${yours.join(", ")}, and okb didn't write ${yours.length === 1 ? "it" : "them"}, so okb docs won't replace ${yours.length === 1 ? "it" : "them"}. Write the pages to an empty or new folder (--out <folder>).`);
  }
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
  }
  return Object.keys(files).sort();
}

/**
 * Write a changed-only view into `dir`, first removing pages an earlier run wrote there (they carry the banner)
 * that this view doesn't include, so a folder reused for a second `--changed` doesn't keep the first one's pages.
 * `rules-in-context.md` is a separate view of the same folder and stays.
 */
export function writeChangedPages(dir: string, files: DocFiles): string[] {
  for (const old of listMarkdown(dir)) {
    if (old in files || old === "rules-in-context.md") continue;
    if (readFileSync(join(dir, old), "utf8").startsWith(BANNER)) rmSync(join(dir, old));
  }
  return writePages(dir, files);
}

function listMarkdown(dir: string): string[] {
  const out: string[] = [];
  const walk = (rel: string) => {
    let entries;
    try {
      entries = readdirSync(join(dir, rel), { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const p = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".md")) out.push(p);
    }
  };
  walk("");
  return out;
}
