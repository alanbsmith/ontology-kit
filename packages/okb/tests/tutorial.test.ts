// The tutorial engine (examples/lib/tutorial.ts): it runs the `okb` blocks in a folder of markdown
// sources and writes pages with real output, graph snapshots and a transcript.
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, it } from "node:test";
import { buildTutorial, splitArgs } from "../examples/lib/tutorial.ts";

const made: string[] = [];
after(() => made.forEach((d) => rmSync(d, { recursive: true, force: true })));

/** A scratch example named `demo` with the given sources. */
function demo(sources: Record<string, string>): string {
  const parent = mkdtempSync(join(tmpdir(), "okb-tutorial-"));
  made.push(parent);
  const dir = join(parent, "demo");
  mkdirSync(join(dir, "tutorial-src"), { recursive: true });
  for (const [name, text] of Object.entries(sources)) writeFileSync(join(dir, "tutorial-src", name), text);
  return dir;
}
const build = (dir: string) => buildTutorial({ dir, date: "2026-09-23", transcript: { title: "Demo", intro: ["Intro."] } });

describe("splitArgs", () => {
  it("splits like a shell: quotes group, backslash escapes", () => {
    assert.deepEqual(splitArgs(`okb cq add "Is it red?" --why 'a "b"' x\\ y a="b c"`), ["okb", "cq", "add", "Is it red?", "--why", 'a "b"', "x y", "a=b c"]);
    assert.deepEqual(splitArgs(`a "" b`), ["a", "", "b"]);
    assert.throws(() => splitArgs(`okb "oops`), /unclosed/);
  });
});

describe("tutorial engine", () => {
  const intro = "# Intro\n\nMake it.\n\n```okb\nokb init demo --name \"Demo\"\n```\n";
  const step = "# Step 1\n\nText.\n\n```okb\nokb scope --domain \"Tea\" --purpose \"Brew\" \\\n  --users drinkers\nokb cq add \"Is it hot?\"\n```\n\n```bash\ncd demo\n```\n\n```okb fails\nokb class add Wines --parent Wine\n```\n";

  it("runs blocks in order, shows commands with output, and writes pages, snapshots and a transcript", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": step.replace("```okb fails\nokb class add Wines --parent Wine\n```\n", "```okb fails\nokb class add Tea --parent Missing\n```\n") });
    const pages = build(dir);
    assert.deepEqual(pages.map((p) => [p.number, p.title]), [[0, "Intro"], [1, "Step 1"]]);
    const page = readFileSync(join(dir, "tutorial", "1-scope.md"), "utf8");
    assert.match(page, /^<!-- Generated by `pnpm example` from tutorial-src\/1-scope\.md\. Don't edit/);
    assert.match(page, /```bash\nokb scope --domain "Tea" --purpose "Brew" \\\n {2}--users drinkers\nokb cq add "Is it hot\?"\n```\n\n```text\nDemo\n/, "commands as written, in a block with no output or prompt");
    assert.match(page, /\nAdded cq\.[0-9a-z]{6}\.\n```/, "the output is in its own block");
    assert.doesNotMatch(page, /\$ okb/, "no prompts on a page, so a copy pastes cleanly");
    assert.match(page, /```bash\ncd demo\n```/, "other code blocks pass through");
    assert.match(page, /```bash\nokb class add Tea --parent Missing\n```\n\n```text\n✗ /, "a block that must fail shows the error");
    // The init output names the folder, not the machine's absolute path.
    const first = readFileSync(join(dir, "tutorial", "0-intro.md"), "utf8");
    assert.match(first, /Created ontology 'Demo' in demo\n/);
    assert.match(readFileSync(join(dir, "TRANSCRIPT.md"), "utf8"), /```console\n\$ okb init demo --name "Demo"\n✓ Created/, "the transcript keeps command and output together");
    // The graph after each step page (not the introduction).
    assert.ok(!existsSync(join(dir, "tutorial", "graph", "step-0.json")));
    const graph = JSON.parse(readFileSync(join(dir, "tutorial", "graph", "step-1.json"), "utf8"));
    assert.equal(graph.step, 1);
    assert.ok(graph.nodes.some((n: any) => n.type === "CompetencyQuestion"));
    assert.ok(Array.isArray(graph.edges));
    assert.match(readFileSync(join(dir, "TRANSCRIPT.md"), "utf8"), /^# Demo\n\nIntro\.\n\n## Intro\n[\s\S]*## Step 1\n/);
  });

  it("writes no pages with pages: false, but keeps the snapshots and the transcript", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": "# Step 1\n\n```okb\nokb cq add \"Is it hot?\"\n```\n" });
    buildTutorial({ dir, date: "2026-09-23", pages: false, transcript: { title: "Demo", intro: ["Intro."] } });
    assert.ok(!existsSync(join(dir, "tutorial", "0-intro.md")) && !existsSync(join(dir, "tutorial", "1-scope.md")));
    assert.ok(existsSync(join(dir, "tutorial", "graph", "step-1.json")));
    assert.ok(existsSync(join(dir, "TRANSCRIPT.md")));
  });

  it("rebuilds from nothing and gives identical files each time", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": "# Step 1\n\n```okb\nokb cq add \"Is it hot?\"\n```\n" });
    build(dir);
    const before = readFileSync(join(dir, "nodes.json"), "utf8");
    writeFileSync(join(dir, "stale.txt"), "left over");
    build(dir);
    assert.equal(readFileSync(join(dir, "nodes.json"), "utf8"), before);
    assert.ok(!existsSync(join(dir, "stale.txt")), "everything but the sources is deleted first");
    assert.match(before, /2026-09-23|Tea|Demo/);
    assert.match(readFileSync(join(dir, "okb.json"), "utf8"), /"created": "2026-09-23"/, "dates are pinned");
  });

  it("fails a command that errors, naming the file, line and command", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": "# Step 1\n\nText.\n\n```okb\nokb class add Wines --parent Wine\n```\n" });
    assert.throws(() => build(dir), (e: Error) => /tutorial-src\/1-scope\.md:5: command failed: okb class add Wines --parent Wine/.test(e.message));
  });

  it("fails a block marked `fails` whose command works", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": "# Step 1\n\n```okb fails\nokb cq add \"Is it hot?\"\n```\n" });
    assert.throws(() => build(dir), /1-scope\.md:3: this command should have failed/);
  });

  it("includes a file an earlier command wrote, and names the file when it is missing", () => {
    const dir = demo({ "0-intro.md": intro, "1-scope.md": "# Step 1\n\n```okb\nokb diagram --out d.md\n```\n\n```include\nd.md\n```\n" });
    build(dir);
    const page = readFileSync(join(dir, "tutorial", "1-scope.md"), "utf8");
    assert.ok(page.includes(readFileSync(join(dir, "d.md"), "utf8").trimEnd()), "the file's text is on the page");
    assert.throws(() => build(demo({ "0-intro.md": intro, "1-scope.md": "# S\n\n```include\nnope.md\n```\n" })), /1-scope\.md:3: include: no file 'nope\.md'/);
  });

  it("refuses a command without `okb`, an unknown option and a badly named page", () => {
    assert.throws(() => build(demo({ "0-intro.md": "# A\n\n```okb\nscope\n```\n" })), /every command starts with 'okb'/);
    assert.throws(() => build(demo({ "0-intro.md": "# A\n\n```okb loud\nokb status\n```\n" })), /unknown option 'loud'/);
    assert.throws(() => build(demo({ "intro.md": "# A\n" })), /named N-slug\.md/);
  });
});
